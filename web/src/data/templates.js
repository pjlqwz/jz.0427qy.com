// 按行业取同组其他模板，用于详情页底部推荐
export function siblings(list, item, n = 3) {
  // 组内排序口径与 /template/ 列表一致：能看真站的排前面（2026-10-21）。
  // 否则详情页底部可能推荐三张只有静态封面的站，客户刚看完能翻页的真站，
  // 往下一点又被降级体验。
  const byLive = (a, b) => Number(!!b.demo) - Number(!!a.demo);
  const same = list.filter((x) => x.industry === item.industry && x.slug !== item.slug).sort(byLive);
  const other = list.filter((x) => x.industry !== item.industry && x.slug !== item.slug).sort(byLive);
  return [...same, ...other].slice(0, n);
}
